// Консервативные демонстрационные правила. Это не диагностика локомотива и не приказ ДНЦ.
export const INCIDENT_TYPES = [
  { code: 'sensor-vibration', label: 'Нестабильный вспомогательный датчик / вибрация без признаков отказа безопасности' },
  { code: 'aux-computer', label: 'Сбой вспомогательного бортового компьютера' },
  { code: 'brake-hose', label: 'Разрыв рукава тормозной магистрали' },
  { code: 'wheel-jam', label: 'Заклинивание колёсной пары' },
  { code: 'diesel-failure', label: 'Отказ дизеля' },
  { code: 'track-obstacle', label: 'Препятствие или посторонний предмет на пути' },
  { code: 'smoke-fire', label: 'Задымление или пожар в составе' },
  { code: 'unknown', label: 'Неизвестная неисправность или происшествие' }
];

const typeByCode = new Map(INCIDENT_TYPES.map(item => [item.code, item]));

export function classifyIncident(code, crewVerified = false) {
  const type = typeByCode.get(code);
  if (!type) throw new Error('Unknown incident type');
  if (typeof crewVerified !== 'boolean') throw new Error('Invalid crew verification');

  const common = { code, title: type.label, method: 'Демонстрационное правило по типу события; вероятность и срок ремонта не рассчитаны', requiresDispatcherReview: true };
  if (code === 'sensor-vibration') return {
    ...common, level: 1, levelName: 'Ранний риск', duration: 'Не оценивается',
    reason: 'Описан вспомогательный датчик без признаков отказа систем безопасности. При появлении таких признаков требуется новая оценка.',
    nextStep: 'Уточнить показания и подтвердить состояние у локомотивной бригады. Планировать осмотр по действующим процедурам.'
  };
  if (code === 'aux-computer' && crewVerified) return {
    ...common, level: 2, levelName: 'Проверенная локальная неисправность', duration: '10–25 мин — только сценарный ориентир',
    reason: 'Бригада подтвердила, что сбой вспомогательного компьютера не затрагивает тормоза, сигнализацию и системы безопасности и может быть устранён на месте.',
    nextStep: 'Уточнить фактический прогноз ремонта у бригады. Решение о помощи и движении принимает ответственный персонал.'
  };
  if (code === 'aux-computer') return {
    ...common, level: 3, levelName: 'Высокая критичность / нет проверки', duration: 'Не определено',
    reason: 'Влияние сбоя компьютера на системы безопасности не подтверждено. Понижать уровень до проверки нельзя.',
    nextStep: 'Связаться с бригадой и установить затронутые системы. Действовать по инструкциям для фактического состояния поезда.'
  };
  const reasons = {
    'brake-hose': 'Нарушение тормозной магистрали затрагивает безопасность торможения; нельзя автоматически считать его мелким ремонтом.',
    'wheel-jam': 'Заклинивание колёсной пары может препятствовать безопасному движению.',
    'diesel-failure': 'Отказ тяги может потребовать помощи и изменения пропуска поездов.',
    'track-obstacle': 'Препятствие на пути требует проверки места и состояния инфраструктуры.',
    'smoke-fire': 'Задымление или пожар могут угрожать людям и подвижному составу.',
    unknown: 'Признаки и последствия события неизвестны; безопасное понижение уровня невозможно.'
  };
  return {
    ...common, level: 3, levelName: 'Высокая критичность / требуется проверка', duration: 'Не определено',
    reason: reasons[code],
    nextStep: 'Уточнить место, время и причину у бригады; при необходимости организовать помощь и ограждение согласно действующим инструкциям. Автоматического вызова нет.'
  };
}
